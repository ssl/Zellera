export const render = (p) => {
  const prefix = clientString('help.linkPrefix') ?? 'pages/';
  const club = clientString('help.clubPage') ?? 'club';
  return [p.caption, ...p.lines].join('\n').replace(/\{([A-Za-z_.]+)\}/g, (all, key) => String((key.startsWith('names.') ? displayNames()[key.slice(6)] : gameRules()[key]) ?? all))
    .replaceAll('event:pages/club"', `event:${prefix}${club}"`).replaceAll('event:pages/', `event:${prefix}`);
};
